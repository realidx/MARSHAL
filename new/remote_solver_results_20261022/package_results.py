"""Losslessly archive every CPU oracle run and build a provenance index."""
import hashlib,json,subprocess,tarfile
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2];OUT=Path(__file__).resolve().parent
SOURCE=Path('/home/e/e1300530/tmp/oracle_cpu_20261021')
RUNS=[('probe','game_oracle_remote_v1','probe','986645'),('base','game_oracle_remote_v1','base','986646'),('extended','game_oracle_remote_v1','extended','986695'),('repair26','game_oracle_repair_v3','repair','988647'),('backward34','game_oracle_experiments_v4','backward-34','989122_0'),('sparse6','game_oracle_experiments_v4','sparse-6','989122_1'),('staged24','game_oracle_experiments_v4','staged-24','989122_2'),('staged15','game_oracle_experiments_v4','staged-remaining15','989412')]
def sha(p):
 h=hashlib.sha256()
 with p.open('rb') as f:
  for b in iter(lambda:f.read(1024*1024),b''):h.update(b)
 return h.hexdigest()
def read(p):return json.loads(p.read_text())
def main():
 runs={};paths={}
 for label,bundle,name,job in RUNS:
  p=SOURCE/bundle/'remote_runs'/name;done=read(p/'COMPLETE.json');s=read(p/'summary.json');assert done['execution_complete']
  assert sha(p/'summary.json')==done['summary_sha256']
  assert sha(p/'ARTIFACTS.json')==done['artifacts_sha256']
  for rel,h in read(p/'ARTIFACTS.json').items():assert sha(p/rel)==h,(label,rel)
  paths[label]=p;runs[label]=dict(job=job,path=str(p.relative_to(SOURCE)),counts=s['counts'],scope=s['expected'],unavailable_indices=[r['index'] for r in s['results'] if r['status']!='certified'],snapshot_sha256=sha(p/'pipeline_snapshot.json'),summary_sha256=sha(p/'summary.json'),final_audit='hash-only; per-reference independent certification was performed during solving')
 selected={}
 for label in ['extended','repair26','staged24']:
  p=paths[label]
  for r in read(p/'summary.json')['results']:
   if r['status']!='certified':continue
   assert r['index'] not in selected
   folder=p/r['execution'];record=read(folder/'result.json')
   assert record['status']=='certified' and record['full_native_terminal'] and record['independent_certificate']
   assert sha(folder/'reference.npz')==record['reference_sha256']
   selected[r['index']]=dict(index=r['index'],parent_id=r['parent_id'],run=label,reference_path=str((folder/'reference.npz').relative_to(SOURCE)),result_path=str((folder/'result.json').relative_to(SOURCE)),reference_sha256=record['reference_sha256'],result_sha256=sha(folder/'result.json'),source_bundle_sha256=record['source_bundle_sha256'])
 assert len(selected)==85 and len({x['parent_id'] for x in selected.values()})==85
 remaining=sorted(set(range(100))-selected.keys())
 (OUT/'SUMMARY.json').write_text(json.dumps(dict(certified_union=85,total_parents=100,unavailable=15,unavailable_indices=remaining,runs=runs,selection='65 preserved base references plus9 extended plus10repair plus1staged24; retain original per-reference source identities',limits=['Not a single homogeneous solver-version run','Remaining15 are missing labels, not zero-signal games','No Q/S/D or model training performed','No new post-run full recertification; final run audits hash-only']),indent=2)+'\n')
 (OUT/'CERTIFIED_REFERENCES.json').write_text(json.dumps(dict(source_root=str(SOURCE),references=[selected[i] for i in sorted(selected)]),indent=2)+'\n')
 accounting=OUT/'SCHEDULER_ACCOUNTING.txt'
 with accounting.open('w') as f:subprocess.run(['sacct','-j','986645,986646,986695,988647,989122,989412','--format=JobID,JobName%35,State,Elapsed,TotalCPU,AllocCPUS,MaxRSS,ExitCode,NodeList','-P'],stdout=f,check=True)
 raw=OUT/'raw';raw.mkdir(exist_ok=True);archive=raw/'all-oracle-runs.tar.gz';entries=[]
 with tarfile.open(archive,'w:gz',compresslevel=6) as tar:
  for f in sorted(SOURCE.rglob('*')):
   if not f.is_file() or '.venv' in f.relative_to(SOURCE).parts or '__pycache__' in f.parts:continue
   if f.is_symlink():raise ValueError('Unexpected evidence symlink '+str(f))
   rel=f.relative_to(SOURCE).as_posix();entries.append(dict(path=rel,source=str(f),size=f.stat().st_size,sha256=sha(f)));tar.add(f,arcname=rel,recursive=False)
 manifest=dict(source_root=str(SOURCE),excluded=['.venv virtualenv binaries/packages; exact package versions in preflight/environment-packages.txt','__pycache__ generated bytecode'],files=entries,archive=dict(path=archive.name,size=archive.stat().st_size,sha256=sha(archive)))
 (raw/'MANIFEST.json').write_text(json.dumps(manifest,indent=2)+'\n')
 print('ARCHIVED',len(entries),'FILES',archive.stat().st_size,'BYTES','CERTIFIED',len(selected),'REMAINING',remaining)
if __name__=='__main__':main()
