"""Per-entrance certified cutoff references and explicit training contract.

Public prefixes are generated by a world-independent uniform policy. The
public posterior is therefore the parent's prior; each root information cell
conditions it on own type and received private answers. Every entrance is
solved afresh with its own next-own horizon. No internal parent-tree label is
silently reused with a shifted endpoint.
"""
